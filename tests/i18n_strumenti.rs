fn non_tradotti(l: Lang) -> Vec<&'static str> {
    set(l);
    MESSAGGI.iter().copied().filter(|m| tr(m) == *m).collect()
}

#[test]
fn gli_errori_dei_profili_si_traducono_in_tutte_le_lingue() {
    for l in [Lang::En, Lang::Es, Lang::De, Lang::Fr, Lang::Pt] {
        let v = non_tradotti(l);
        assert!(v.is_empty(), "{l:?}: {} messaggi in italiano:\n{}", v.len(), v.join("\n"));
    }
}
